const assert = require('assert').strict;
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));

// Runs within browser-review's isolated API fixtures, never against business writes.
module.exports = async ({ ev, cdp, route, shot, component, requests }) => {
  const result = {};
  const settings = () => component('AppearancePanel');
  const set = (key, value) => ev(`${settings()}.set(${JSON.stringify(key)},${JSON.stringify(value)}).then(()=>true)`);
  const snapshot = () => ev(`({mode:document.documentElement.dataset.experience,motion:document.documentElement.dataset.motion,glass:document.documentElement.dataset.homeGlass,theme:document.documentElement.dataset.theme,nav:document.querySelector('#header')?.className,prefs:JSON.parse(localStorage.getItem('cdutetc:appearance'))})`);
  const click = async selector => {
    const point = await ev(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});el.scrollIntoView({block:'nearest'});const r=el.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2};})()`);
    for (const type of ['mouseMoved', 'mousePressed', 'mouseReleased']) await cdp('Input.dispatchMouseEvent', { type, ...point, ...(type==='mouseMoved'?{}:{button:'left',clickCount:1}) });
    return point;
  };
  const close = async () => { await ev(`${component('ProfileMenu')}.$refs.popover.close(); true`); await sleep(280); };
  await route('/home');
  await set('experience','standard'); await set('autoContest',true); await set('motion','full');
  await set('spotlight',true); await set('homeGlass',true); await set('morph',true);
  await set('navigation','dynamic'); await set('theme','light');
  await sleep(500);
  await ev(`window.appearanceAnimations=[];window.appearanceNativeAnimate=Element.prototype.animate;Element.prototype.animate=function(frames,options){if(options?.pseudoElement||this.classList?.contains('morph-popover'))appearanceAnimations.push({frames,options,morph:this.classList.contains('morph-popover')});return appearanceNativeAnimate.call(this,frames,options)};true`);
  const order = await ev(`['.nav-notifications','.theme-toggle','.nav-account'].map(s=>document.querySelector('#header '+s).getBoundingClientRect().left)`);
  assert(order[0]<order[1] && order[1]<order[2], 'theme shortcut lies between notification and avatar');
  const beforeEffects = requests.length;
  const origin = await click('#header .theme-toggle');
  await sleep(500);
  const reveal = await ev('appearanceAnimations.find(x=>x.options.pseudoElement)');
  assert(reveal, 'actual one-click shortcut starts a native theme reveal');
  const start = reveal.frames[0].clipPath.match(/M ([\d.-]+) ([\d.-]+)/).slice(1).map(Number);
  assert(Math.abs(start[0]-origin.x)<1 && Math.abs(start[1]-origin.y)<1);
  assert.equal(await ev('document.documentElement.dataset.theme'), 'dark');
  assert(await ev("!document.querySelector('.appearance-control')"), 'authenticated layout settings live in the profile menu');
  await shot('appearance-theme-shortcut-wave');
  await sleep(1100);
  await click('#header .nav-account'); await sleep(400);
  assert((await ev('appearanceAnimations.filter(x=>x.morph)')).length>0, 'profile unfolds from its trigger');
  await shot('appearance-profile-dark');
  await click('.profile-appearance-link'); await sleep(150);
  assert(await ev("document.querySelector('.profile-appearance').getBoundingClientRect().height>0"));
  await shot('appearance-settings-dark');
  await close();
  const card = await ev("(()=>{const r=document.querySelector('.home-photo').getBoundingClientRect();return {x:r.x+80,y:r.y+80}})()");
  await cdp('Input.dispatchMouseEvent',{type:'mouseMoved',...card}); await sleep(100);
  assert(await ev("document.querySelector('.home-photo').classList.contains('spotlight-active')"));
  const stableLight = await ev("document.querySelector('.home-photo').style.cssText");
  await sleep(400);
  assert.equal(await ev("document.querySelector('.home-photo').style.cssText"), stableLight, 'no idle spotlight updates');
  await shot('appearance-home-glass-dark');
  await set('theme','light'); await shot('appearance-home-glass-light');
  assert.notEqual(await ev("getComputedStyle(document.querySelector('.home-glass-sheet')).backdropFilter"), 'none');
  result.effects = {shortcutOrigin:origin,themeDuration:reveal.options.duration,profileMorph:true,spotlight:true,idleSpotlightStable:true};
  const effectRequests = requests.length-beforeEffects;
  assert.equal(effectRequests,0,'theme, profile and spotlight effects do not request APIs');
  await click('#header .nav-account'); await sleep(400); await click('.profile-appearance-link');
  await click('.experience-options .el-radio-button:nth-child(2)'); await sleep(100);
  const simple = await snapshot();
  assert.equal(simple.mode,'minimal'); assert.equal(simple.motion,'reduced'); assert.equal(simple.glass,'off'); assert(simple.nav.includes('nav-normal'));
  assert(await ev("!document.querySelector('.spotlight-active')"));
  assert.equal(await ev("getComputedStyle(document.querySelector('#header')).transitionDuration"),'0s');
  await close(); await shot('appearance-minimal');
  await set('experience','standard');
  assert.equal((await snapshot()).glass,'on');
  const prefs = await ev("localStorage.getItem('cdutetc:appearance')");
  await route('/contest/1/problem/P1000/full-screen');
  const contest = await snapshot();
  assert.equal(contest.mode,'minimal'); assert.equal(contest.motion,'reduced');
  assert.equal(await ev("localStorage.getItem('cdutetc:appearance')"), prefs, 'contest override does not erase preferences');
  await shot('appearance-contest-minimal');
  await set('autoContest',false);
  assert.equal((await snapshot()).mode,'standard','user can opt out while in a contest');
  await set('autoContest',true); await route('/home');
  assert.equal((await snapshot()).mode,'standard'); assert.equal((await snapshot()).motion,'full');
  result.contest = {automaticMinimal:true,preferencesPreserved:true,optOutWorks:true,restoredOnExit:true};
  await set('spotlight',false); await set('homeGlass',false);
  assert.equal((await snapshot()).glass,'off');
  await cdp('Input.dispatchMouseEvent',{type:'mouseMoved',...card}); await sleep(100);
  assert(await ev("!document.querySelector('.spotlight-active')"));
  await set('spotlight',true); await set('homeGlass',true);
  await cdp('Page.reload'); await sleep(1800);
  assert.equal((await snapshot()).prefs.motion,'full'); assert.equal((await snapshot()).prefs.autoContest,true);
  await cdp('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await sleep(500);
  const mobileCenters = await ev("['.theme-toggle','[aria-label=通知]','.nav-account'].map(s=>{const r=document.querySelector('.mobile-nav '+s).getBoundingClientRect();return r.y+r.height/2;})");
  assert(Math.max(...mobileCenters)-Math.min(...mobileCenters)<5,'mobile notification, theme and avatar align');
  await click('.mobile-nav .nav-account'); await sleep(400); await click('.profile-appearance-link'); await sleep(150);
  const mobile = await ev("(()=>{const p=[...document.querySelectorAll('.morph-popover')].find(x=>x.offsetHeight),r=p.getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,viewport:innerHeight,overflow:document.documentElement.scrollWidth>innerWidth}})()");
  assert(!mobile.overflow && mobile.left>=0 && mobile.right<=390 && mobile.top>=0 && mobile.bottom<=mobile.viewport);
  await shot('appearance-settings-mobile'); await close();
  await cdp('Emulation.setDeviceMetricsOverride',{width:1440,height:1080,deviceScaleFactor:1,mobile:false}); await sleep(500);
  // Closing a panel must release document/window listeners and ResizeObservers.
  const documentObject = (await cdp('Runtime.evaluate',{expression:'document'})).result.objectId;
  const listeners = async () => (await cdp('DOMDebugger.getEventListeners',{objectId:documentObject})).listeners.filter(x=>['pointerdown','keydown','focusin'].includes(x.type)).length;
  const baseline = await listeners();
  for (let i=0;i<3;i++) { await click('#header .nav-account'); await sleep(360); await close(); }
  assert.equal(await listeners(),baseline,'profile cycles release document listeners');
  await cdp('Performance.enable');
  const metrics = async () => Object.fromEntries((await cdp('Performance.getMetrics')).metrics.map(x=>[x.name,x.value]));
  const beforeIdle = await metrics();
  const idleRequests = requests.length;
  await sleep(800);
  const afterIdle = await metrics();
  await cdp('Emulation.setCPUThrottlingRate',{rate:4});
  await click('#header .theme-toggle'); await sleep(1750);
  assert.equal(await ev('document.documentElement.dataset.theme'),'dark');
  await click('#header .nav-account'); await sleep(500); await click('.profile-appearance-link');
  await click('.experience-options .el-radio-button:nth-child(2)'); await sleep(150);
  assert.equal((await snapshot()).mode,'minimal');
  await close(); await cdp('Emulation.setCPUThrottlingRate',{rate:1});
  await set('experience','standard');
  result.performance = {effectOnlyRequests:effectRequests,idleRequests:requests.length-idleRequests,idleWindowMs:800,idleTaskMs:Math.round((afterIdle.TaskDuration-beforeIdle.TaskDuration)*1000),idleLayouts:afterIdle.LayoutCount-beforeIdle.LayoutCount,documentListenersStable:true,cpu4xFunctionalCheck:true,note:'headless browser checks, not GPU FPS or a 400-user server load test'};
  // The only API calls made in this section are ordinary route/reload reads.
  result.performance.routeAndReloadReads = requests.length-beforeEffects;
  result.mobile = mobile;
  await set('motion','system'); await set('theme','light');
  await route('/problem/P1000');
  result.validated = true;
  return result;
};
